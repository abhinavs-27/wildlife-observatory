#!/usr/bin/env python3
"""Benchmark MegaDetector + SpeciesNet: load time, per-image time and peak RSS per stage.

Run inside the worker environment:
  cd worker && uv run python ../scripts/benchmark.py --images ../samples/images --n 20 \
      --out ../docs/benchmarks.md [--device cpu] [--threads 4]

Use --device cpu to approximate a CPU-only box; on the Pi 400 run it inside the worker
container. Results are appended to the markdown file so Mac and Pi numbers sit side by side.
"""

from __future__ import annotations

import argparse
import os
import platform
import resource
import statistics
import sys
import time
from datetime import datetime
from pathlib import Path


def rss_mb() -> float:
    import psutil
    return psutil.Process(os.getpid()).memory_info().rss / 1e6


def peak_mb() -> float:
    r = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return r / 1e6 if sys.platform == "darwin" else r / 1e3  # bytes on macOS, KB on Linux


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--images", type=Path, required=True)
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--device", choices=["auto", "cpu"], default="auto")
    ap.add_argument("--threads", type=int, default=0)
    args = ap.parse_args()

    dev = "cpu" if args.device == "cpu" else None
    import torch
    if args.threads:
        torch.set_num_threads(args.threads)

    from PIL import Image
    sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "worker" / "src"))
    from observatory_worker.models import SpeciesNetModels

    files = sorted(p for p in args.images.rglob("*") if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    files = files[: args.n]
    base = rss_mb()
    t = time.perf_counter()
    m = SpeciesNetModels(load_detector=True, load_classifier=False, device=dev)
    det_load = time.perf_counter() - t
    after_det = rss_mb()
    t = time.perf_counter()
    m2 = SpeciesNetModels(load_detector=False, load_classifier=True, device=dev)
    cls_load = time.perf_counter() - t
    after_cls = rss_mb()

    det_t, cls_t, n_dets = [], [], 0
    for f in files:
        img = Image.open(f)
        img.load()
        t = time.perf_counter()
        dets = m.detect(img)
        det_t.append(time.perf_counter() - t)
        animals = [dict(d, detection_id=i) for i, d in enumerate(dets)
                   if d["category"] == "animal" and d["conf"] >= 0.2]
        if animals:
            t = time.perf_counter()
            m2.classify(img, animals, "USA", "NJ")
            cls_t.append(time.perf_counter() - t)
            n_dets += len(animals)

    def s(xs):
        if not xs:
            return "n/a"
        xs = sorted(xs[1:] or xs)  # drop first (warm-up)
        return f"median {statistics.median(xs):.2f}s, p90 {xs[int(len(xs) * 0.9) - 1 if len(xs) > 1 else 0]:.2f}s"

    lines = [
        f"### {platform.node()} — {platform.system()} {platform.machine()}, "
        f"device={getattr(m, 'device', '?')}, threads={torch.get_num_threads()} "
        f"({datetime.now():%Y-%m-%d %H:%M})",
        "",
        f"- Images: {len(files)} real NACTI camera-trap photos; {n_dets} animal detections classified",
        f"- Detector (MegaDetector v5a) load: {det_load:.1f}s, +{after_det - base:.0f} MB RSS",
        f"- Classifier + ensemble (SpeciesNet {m2.classifier_info['version']}) load: {cls_load:.1f}s, "
        f"+{after_cls - after_det:.0f} MB RSS",
        f"- Detect per image: {s(det_t)}",
        f"- Classify + ensemble per image with animals: {s(cls_t)}",
        f"- Peak RSS (both models resident): {peak_mb():.0f} MB",
        "",
    ]
    text = "\n".join(lines)
    print(text)
    if args.out:
        if not args.out.exists():
            args.out.write_text("# Benchmarks\n\nGenerated by `scripts/benchmark.py`. "
                                "Pi 400 numbers will be added once the hardware arrives.\n\n")
        with open(args.out, "a") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
